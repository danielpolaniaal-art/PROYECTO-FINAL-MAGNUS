def env_flag(name, default=False):
    """Lee una variable de entorno como verdadero/falso ('1', 'true', 'si', 'on')."""
    value = os.environ.get(name)
    if value is None:
        return default
    return value.strip().lower() in ('1', 'true', 'yes', 'si', 'sí', 'on')


def load_secret_key():
    """
    La clave secreta firma las sesiones y los tokens CSRF. Como la página será pública,
    NO puede ser una clave conocida. Orden: variable DJANGO_SECRET_KEY -> archivo local
    ".secret_key" (se genera solo la primera vez, junto a manage.py) -> clave temporal.
    """
    key = os.environ.get('DJANGO_SECRET_KEY', '').strip()
    if key:
        return key
    key_file = BASE_DIR / '.secret_key'
    try:
        if key_file.exists():
            saved = key_file.read_text(encoding='utf-8').strip()
            if saved:
                return saved
        key = secrets.token_urlsafe(64)
        key_file.write_text(key, encoding='utf-8')
        return key
    except OSError:
        return secrets.token_urlsafe(64)  # sin permisos de escritura: las sesiones se reinician con el servidor


SECRET_KEY = load_secret_key()

