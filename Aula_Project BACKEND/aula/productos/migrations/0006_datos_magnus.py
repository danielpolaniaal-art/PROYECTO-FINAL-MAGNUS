def cargar_datos(apps, schema_editor):
    User = apps.get_model("auth", "User")
    Profile = apps.get_model("productos", "CompanyProfile")
    Product = apps.get_model("productos", "Product")
    SaleItem = apps.get_model("productos", "SaleItem")
    Category = apps.get_model("productos", "Category")
    Client = apps.get_model("productos", "Client")

    # 1. Los usuarios con el rol anterior "Usuario" pasan a "Asesor de ventas"; ya no hay nombre de empresa.
    Profile.objects.filter(role="Usuario").update(role="Asesor de ventas")
    Profile.objects.update(company=EMPRESA)

    # 2. Administrador inicial con acceso también como usuario.
    admin = User.objects.filter(username=ADMIN_INICIAL).first()
    if admin:
        Profile.objects.filter(user_id=admin.id).update(role="Administrador", dual=True)

    # 3. Superadministrador inicial (nadie puede quitarle el rol).
    superadmin, creado = User.objects.get_or_create(
        username=SUPERADMIN_INICIAL,
        defaults={"email": SUPERADMIN_INICIAL, "first_name": "Superadministrador"},
    )
    if creado:
        superadmin.password = make_password("Magnus2026Super")
        superadmin.save(update_fields=["password"])
    Profile.objects.update_or_create(user_id=superadmin.id, defaults={"role": "Superadministrador", "company": EMPRESA})

    # 4. Se retiran los productos de ejemplo de electrónica (ELE-001 ... ELE-006).
    for producto in Product.objects.filter(sku__startswith="ELE-"):
        if SaleItem.objects.filter(product_id=producto.id).exists():
            producto.active = False
            producto.save(update_fields=["active"])
        else:
            producto.delete()

    # 5. Categorías y catálogo de Magnus SIG.
    for nombre in CATEGORIAS:
        Category.objects.get_or_create(name=nombre)
    dueno = admin or superadmin
    for tipo, nombre, sku, categoria, stock, minimo, costo, precio, desc in PRODUCTOS:
        Category.objects.get_or_create(name=categoria)
        Product.objects.get_or_create(
            owner=dueno, sku=sku,
            defaults={"kind": tipo, "name": nombre, "category": categoria, "description": desc,
                      "stock": stock, "minimum_stock": minimo, "cost": costo, "price": precio, "icon": "box"},
        )

    # 6. Clientes de ejemplo.
    for nombre, documento, telefono in CLIENTES:
        if not Client.objects.filter(name=nombre).exists():
            Client.objects.create(name=nombre, document=documento, phone=telefono)


